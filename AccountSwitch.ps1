# Shared local file switch core. Never return credential bytes or exception details.
function Test-SwitchName {
    param([string]$Name)
    return (-not [string]::IsNullOrWhiteSpace($Name) -and
        $Name -ceq $Name.Trim() -and $Name -notmatch '[<>:"/\\|?*\x00-\x1f]' -and
        $Name -notmatch '[. ]$|^\.|^backup-' -and
        $Name -notmatch '^(CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\.|$)')
}

function ConvertFrom-SwitchJson {
    param([byte[]]$Bytes)
    $text = (New-Object Text.UTF8Encoding($false, $true)).GetString($Bytes).TrimStart([char]0xFEFF)
    if ($text.TrimStart() -notmatch '^\{') { throw '存档格式无效。' }
    return ($text | ConvertFrom-Json -ErrorAction Stop)
}

function Get-SwitchIdentity {
    param([byte[]]$Bytes)
    try {
        $data = ConvertFrom-SwitchJson $Bytes
        $tokens = $data.tokens
        # Login owner is generated by Codex and survives token rotation. The workspace
        # alone is never an identity: many users can share the same workspace.
        $account = $tokens.account_id
        $owner = $tokens.login_owner_id
        $user = $null
        if ($tokens.id_token -is [string]) {
            $parts = $tokens.id_token.Split('.')
            if ($parts.Length -eq 3 -and $parts[0] -and $parts[2]) {
                $payload = $parts[1].Replace('-', '+').Replace('_', '/')
                $payload = $payload.PadRight($payload.Length + ((4 - $payload.Length % 4) % 4), '=')
                $claims = ConvertFrom-SwitchJson ([Convert]::FromBase64String($payload))
                $claim = $claims.'https://api.openai.com/auth'
                $user = if ($claim.chatgpt_user_id) { $claim.chatgpt_user_id } else { $claim.user_id }
                if (-not $account) { $account = $claim.chatgpt_account_id }
                if ($claim.chatgpt_account_id -cne $account) { return $null }
            }
        }
        if ($account -isnot [string] -or [string]::IsNullOrWhiteSpace($account) -or $account -cne $account.Trim()) { return $null }
        if ($user -is [string] -and -not [string]::IsNullOrWhiteSpace($user) -and $user -ceq $user.Trim()) {
            return [pscustomobject]@{ Kind='User'; Account=$account; Owner=$user }
        }
        if ($owner -is [string] -and -not [string]::IsNullOrWhiteSpace($owner) -and $owner -ceq $owner.Trim()) {
            return [pscustomobject]@{ Kind='Login'; Account=$account; Owner=$owner }
        }
    } catch { return $null }
    return $null
}

function Test-SwitchIdentityEqual {
    param($Left, $Right)
    return ($null -ne $Left -and $null -ne $Right -and $Left.Kind -ceq $Right.Kind -and
        $Left.Account -ceq $Right.Account -and $Left.Owner -ceq $Right.Owner)
}

function Assert-SwitchPath {
    param([string]$Path)
    $itemPath = [IO.Path]::GetFullPath($Path)
    while ($itemPath) {
        if (Test-Path -LiteralPath $itemPath) {
            $item = Get-Item -LiteralPath $itemPath -Force -ErrorAction Stop
            if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { throw '路径不可用。' }
        }
        $parent = [IO.Path]::GetDirectoryName($itemPath)
        if ($parent -eq $itemPath) { break }
        $itemPath = $parent
    }
}

