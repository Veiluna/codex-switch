function Test-SwitchBytesEqual {
    param([byte[]]$Left, [byte[]]$Right)
    if ($null -eq $Left -or $null -eq $Right) { return ($null -eq $Left -and $null -eq $Right) }
    return ([Convert]::ToBase64String($Left) -ceq [Convert]::ToBase64String($Right))
}

function Test-SwitchSnapshot {
    param([string]$Path, [bool]$Exists, [byte[]]$Bytes)
    if ((Test-SwitchFileExists $Path) -ne $Exists) { return $false }
    if (-not $Exists) { return $true }
    return (Test-SwitchBytesEqual ([IO.File]::ReadAllBytes($Path)) $Bytes)
}

function Test-SwitchFileExists {
    param([string]$Path)
    try {
        $attributes = [IO.File]::GetAttributes($Path)
        if (($attributes -band [IO.FileAttributes]::Directory) -ne 0) { throw '凭据路径不是普通文件。' }
        return $true
    } catch [IO.FileNotFoundException] { return $false }
      catch [IO.DirectoryNotFoundException] { return $false }
}

function Invoke-SwitchFileReplace {
    param([string]$Source, [string]$Destination, [string]$BackupPath)
    if ($BackupPath) { [IO.File]::Replace($Source, $Destination, $BackupPath) }
    else { [IO.File]::Replace($Source, $Destination, [System.Management.Automation.Language.NullString]::Value) }
}

function Invoke-SwitchFileMove {
    param([string]$Source, [string]$Destination)
    [IO.File]::Move($Source, $Destination)
}

function Write-SwitchAtomic {
    param(
        [string]$Path, [byte[]]$Bytes, [string]$BackupPath,
        [switch]$CheckExpected, [bool]$ExpectedExists, [byte[]]$ExpectedBytes
    )
    Assert-SwitchPath $Path
    $temp = Join-Path ([IO.Path]::GetDirectoryName($Path)) ('.switch-' + [guid]::NewGuid().ToString('N') + '.tmp')
    try {
        $stream = [IO.File]::Open($temp, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
        try { $stream.Write($Bytes, 0, $Bytes.Length); $stream.Flush($true) }
        finally { $stream.Dispose() }
        Assert-SwitchPath $Path
        if ($CheckExpected -and -not (Test-SwitchSnapshot $Path $ExpectedExists $ExpectedBytes)) { throw 'ConcurrentChange' }
        if ($BackupPath) {
            Assert-SwitchPath $BackupPath
            if (Test-Path -LiteralPath $BackupPath) { throw '备份路径已存在。' }
        }
        # Under a snapshot contract, never change primitive based on a second Exists:
        # a newly appeared file must make Move fail, not silently enter Replace.
        $replace = if ($CheckExpected) { $ExpectedExists } else { [IO.File]::Exists($Path) }
        if ($replace) { Invoke-SwitchFileReplace -Source $temp -Destination $Path -BackupPath $BackupPath }
        else { Invoke-SwitchFileMove -Source $temp -Destination $Path }
    } catch {
        if ($CheckExpected -and -not (Test-SwitchSnapshot $Path $ExpectedExists $ExpectedBytes)) { throw 'ConcurrentChange' }
        throw
    } finally {
        if ([IO.File]::Exists($temp)) { [IO.File]::Delete($temp) }
    }
}

function Restore-SwitchAuth {
    param([string]$Path, [bool]$HadAuth, [byte[]]$OriginalBytes, [byte[]]$WrittenBytes, [string]$Accounts)
    # Never knowingly overwrite a foreign update. Each replacement also captures the
    # displaced version, covering the narrow gap between comparison and ReplaceFile.
    if (-not (Test-SwitchSnapshot $Path $true $WrittenBytes)) { return $false }
    $expected = $WrittenBytes
    $desired = $OriginalBytes
    $conflict = $false
    for ($attempt = 0; $attempt -lt 3; $attempt++) {
        $displaced = Join-Path $Accounts ('backup-recovery-' + [guid]::NewGuid().ToString('N') + '_auth.json')
        if (-not $HadAuth -and $attempt -eq 0) {
            # Moving to a unique name is atomic and retains anything that raced with
            # our check. Restore a foreign version only if the active name is absent.
            [IO.File]::Move($Path, $displaced)
            [byte[]]$moved = [IO.File]::ReadAllBytes($displaced)
            if (Test-SwitchBytesEqual $moved $expected) { return (-not [IO.File]::Exists($Path)) }
            if (-not [IO.File]::Exists($Path)) { [IO.File]::Move($displaced, $Path) }
            return $false
        }
        try {
            Write-SwitchAtomic -Path $Path -Bytes $desired -BackupPath $displaced -CheckExpected -ExpectedExists $true -ExpectedBytes $expected
        } catch { return $false }
        [byte[]]$captured = [IO.File]::ReadAllBytes($displaced)
        if (Test-SwitchBytesEqual $captured $expected) {
            return (-not $conflict -and (Test-SwitchSnapshot $Path $true $desired))
        }
        # A foreign rename won the compare/replace gap. Its bytes are now retained;
        # put that actual latest version back only while our own replacement remains.
        $conflict = $true
        $expected = $desired
        $desired = $captured
    }
    return $false
}

function New-SwitchResult {
    param([bool]$Success, [bool]$Changed, [string]$Code, [string]$Message, [string]$BackupPath = '')
    [pscustomobject]@{ Success=$Success; Changed=$Changed; Code=$Code; Message=$Message; BackupPath=$BackupPath }
}

function Invoke-SwitchAccount {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory=$true)][string]$Root,
        [Parameter(Mandatory=$true)][string]$Name,
        [scriptblock]$BeforeWriteGuard = { Test-SwitchDesktopClosed },
        [switch]$AlreadyLocked,
        [byte[]]$ExpectedTargetBytes,
        [Action[byte[]]]$BeforeDeparture
    )
    $lock = $null
    $backup = ''
    $authChanged = $false
    $hadAuth = $false
    try {
        if (-not (Test-SwitchName $Name) -or -not [IO.Path]::IsPathRooted($Root) -or
            $Root -notmatch '^(?:[A-Za-z]:[\\/]|\\\\[^\\/]+[\\/][^\\/]+(?:[\\/]|$))' -or $Root -match '^\\\\[?.]\\') {
            return (New-SwitchResult $false $false 'InvalidPath' '账号名称或本机目录无效。')
        }
        $Root = [IO.Path]::GetFullPath($Root)
        $accounts = Join-Path $Root 'accounts'
        $auth = Join-Path $Root 'auth.json'
        $marker = Join-Path $accounts '.current'
        $lockPath = Join-Path $accounts '.switch.lock'
        foreach ($path in @($Root, $accounts, $auth, $marker, $lockPath)) { Assert-SwitchPath $path }
        if (-not [IO.Directory]::Exists($accounts)) {
            return (New-SwitchResult $false $false 'TargetMissing' '未找到已保存的目标账号。')
        }
        try { if (-not $AlreadyLocked) { $lock = [IO.File]::Open($lockPath, 'OpenOrCreate', 'ReadWrite', 'None') } }
        catch { return (New-SwitchResult $false $false 'Busy' '另一个保存或切换操作正在进行，或账号目录不可写，请稍后重试。') }
        $target = $null
        foreach ($leaf in @(($Name + '_auth.json'), ($Name + '.json'))) {
            $candidate = Join-Path $accounts $leaf
            Assert-SwitchPath $candidate
            if ([IO.File]::Exists($candidate)) { $target = $candidate; break }
        }
        if (-not $target) { return (New-SwitchResult $false $false 'TargetMissing' '未找到已保存的目标账号。') }
        $targetBytes = [IO.File]::ReadAllBytes($target)
        if ($null -ne $ExpectedTargetBytes -and -not (Test-SwitchBytesEqual $targetBytes $ExpectedTargetBytes)) { throw 'ConcurrentChange' }
        try { $null = ConvertFrom-SwitchJson $targetBytes }
        catch { return (New-SwitchResult $false $false 'InvalidTarget' '目标账号存档格式无效，未执行切换。') }
        $guardResult = @(& $BeforeWriteGuard)
        if ($guardResult.Count -ne 1 -or $guardResult[0] -isnot [bool] -or -not $guardResult[0]) {
            return (New-SwitchResult $false $false 'DesktopRunning' '请先完全退出 Codex 桌面端，再切换账号。')
        }
        # The guard can close a process that flushes newer tokens. Snapshot afterwards.
        # Direct typed assignment preserves a zero-length byte[] (pipeline if output does not).
        $hadAuth = Test-SwitchFileExists $auth
        [byte[]]$oldBytes = $null
        if ($hadAuth) { $oldBytes = [IO.File]::ReadAllBytes($auth) }
        if ($hadAuth -and $BeforeDeparture) { $BeforeDeparture.Invoke($oldBytes) }
        if (-not (Test-SwitchSnapshot $target $true $targetBytes)) { throw 'ConcurrentChange' }
        $same = $hadAuth -and (Test-SwitchBytesEqual $oldBytes $targetBytes)
        # Comparing actual bytes makes repeated clicks safe without trusting .current.
        if ($same) {
            if (-not (Test-SwitchSnapshot $auth $true $oldBytes)) { throw 'ConcurrentChange' }
            $recorded = if ([IO.File]::Exists($marker)) { [IO.File]::ReadAllText($marker) } else { $null }
            if ($recorded -cne $Name) {
                Write-SwitchAtomic -Path $marker -Bytes ((New-Object Text.UTF8Encoding($false)).GetBytes($Name))
            }
            if (-not (Test-SwitchSnapshot $auth $true $oldBytes)) { throw 'ConcurrentChange' }
            return (New-SwitchResult $true $false 'AlreadyCurrent' ('当前登录已与“{0}”的存档一致。' -f $Name))
        }
        $activeIdentity = $null
        if ($hadAuth) {
            $backup = Join-Path $accounts ('backup-' + [guid]::NewGuid().ToString('N') + '_auth.json')
            $activeIdentity = Get-SwitchIdentity $oldBytes
            if (Test-SwitchIdentityEqual $activeIdentity (Get-SwitchIdentity $targetBytes)) {
                $targetBytes = $oldBytes
            }
        }
        # 保存和额度网络请求期间桌面端可能重新启动，写入前重新核对。
        $guardResult = @(& $BeforeWriteGuard)
        if ($guardResult.Count -ne 1 -or $guardResult[0] -isnot [bool] -or -not $guardResult[0]) {
            return (New-SwitchResult $false $false 'DesktopRunning' 'Codex 桌面端重新运行或状态无法核实，已停止切换，原登录已保留。')
        }
        # File.Replace captures the actual displaced file, not an earlier read/copy.
        Write-SwitchAtomic -Path $auth -Bytes $targetBytes -BackupPath $backup -CheckExpected -ExpectedExists $hadAuth -ExpectedBytes $oldBytes
        $authChanged = $true
        if ($hadAuth -and -not (Test-SwitchBytesEqual ([IO.File]::ReadAllBytes($backup)) $oldBytes)) {
            $oldBytes = [IO.File]::ReadAllBytes($backup)
            throw 'ConcurrentChange'
        }
        if (-not (Test-SwitchSnapshot $auth $true $targetBytes)) { throw 'ConcurrentChange' }
        if ($hadAuth) {
            # Refresh only the proven owner archive. A marker is a lookup hint, never proof.
            if ([IO.File]::Exists($marker)) {
                $previousName = [IO.File]::ReadAllText($marker).Trim()
                if (Test-SwitchName $previousName) {
                    foreach ($leaf in @(($previousName + '_auth.json'), ($previousName + '.json'))) {
                        $previousPath = Join-Path $accounts $leaf
                        Assert-SwitchPath $previousPath
                        if ([IO.File]::Exists($previousPath)) {
                            if (Test-SwitchIdentityEqual $activeIdentity (Get-SwitchIdentity ([IO.File]::ReadAllBytes($previousPath)))) {
                                Write-SwitchAtomic -Path $previousPath -Bytes $oldBytes
                            }
                            break
                        }
                    }
                }
            }
            if (Test-SwitchIdentityEqual $activeIdentity (Get-SwitchIdentity $targetBytes)) {
                # Selecting the same actual identity must retain its freshest tokens.
                Write-SwitchAtomic -Path $target -Bytes $oldBytes
            }
        }
        Write-SwitchAtomic -Path $marker -Bytes ((New-Object Text.UTF8Encoding($false)).GetBytes($Name))
        if (-not (Test-SwitchSnapshot $auth $true $targetBytes)) { throw 'ConcurrentChange' }
        return (New-SwitchResult $true $true 'Switched' ('已切换到“{0}”，Codex 保持关闭。' -f $Name) $backup)
    } catch {
        $concurrent = ($_.Exception.Message -ceq 'ConcurrentChange')
        if ($authChanged) {
            try {
                $restored = Restore-SwitchAuth -Path $auth -HadAuth $hadAuth -OriginalBytes $oldBytes -WrittenBytes $targetBytes -Accounts $accounts
                if (-not $restored) {
                    return (New-SwitchResult $false $true 'ConcurrentChange' '检测到外部更新，已停止切换。请检查当前登录及 accounts 中保留的原版本、竞争版本后重试。' $backup)
                }
            } catch {
                return (New-SwitchResult $false $true 'RecoveryRequired' '切换未完成，自动恢复失败。请保持 Codex 关闭，使用 accounts 中本次 backup 存档恢复。' $backup)
            }
        }
        if (-not $authChanged -and $backup -and [IO.File]::Exists($backup) -and
            -not (Test-SwitchSnapshot $auth $hadAuth $oldBytes)) {
            return (New-SwitchResult $false $true 'RecoveryRequired' '文件替换未完成，请保持 Codex 关闭并使用 accounts 中本次 backup 存档恢复。' $backup)
        }
        if ($concurrent) {
            return (New-SwitchResult $false $false 'ConcurrentChange' '检测到登录文件外部变更，已停止切换。请检查当前登录后重试。' $backup)
        }
        return (New-SwitchResult $false $false 'WriteFailed' '切换未完成，原登录已保留或恢复。请检查本机文件访问权限。' $backup)
    } finally { if ($lock) { $lock.Dispose() } }
}
